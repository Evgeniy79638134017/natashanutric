const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const docsDir = path.join(__dirname, '..', 'public', 'docs');
if (!fs.existsSync(docsDir)) {
  fs.mkdirSync(docsDir, { recursive: true });
}

function createPDF(filename, title, date, sections) {
  const doc = new PDFDocument({
    size: 'A4',
    margin: 50,
    info: {
      Title: title,
      Author: 'ИП Ерёменко Наталья Сергеевна'
    }
  });

  const filepath = path.join(docsDir, filename);
  doc.pipe(fs.createWriteStream(filepath));

  // Title
  doc.fontSize(20).font('Helvetica-Bold').text(title, { align: 'center' });
  doc.moveDown(0.5);
  doc.fontSize(10).font('Helvetica').fillColor('#666666').text(`Дата вступления в силу: ${date}`, { align: 'center' });
  doc.moveDown(1.5);
  doc.fillColor('#000000');

  // Sections
  sections.forEach(section => {
    doc.fontSize(14).font('Helvetica-Bold').text(section.title);
    doc.moveDown(0.5);
    doc.fontSize(11).font('Helvetica').text(section.content, { align: 'justify', lineGap: 3 });
    doc.moveDown(1);
  });

  doc.end();
  console.log(`Created: ${filepath}`);
}

